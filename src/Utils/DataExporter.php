    private function generateHtmlContent(array $data): string
    {
        $html = "";
        
        // Summary section
        if (isset($data['scanners'])) {
            $html .= "<div class=\"summary\">\n";
            $html .= "<h3>📊 Scan Summary</h3>\n";
            $html .= "<div class=\"summary-grid\">\n";
            
            $html .= "<div class=\"summary-item\">\n";
            $html .= "<div class=\"summary-number\">" . htmlspecialchars($data['target'] ?? 'N/A') . "</div>\n";
            $html .= "<div class=\"summary-label\">Target</div>\n";
            $html .= "</div>\n";
            
            $html .= "<div class=\"summary-item\">\n";
            $html .= "<div class=\"summary-number\">" . htmlspecialchars($data['duration'] ?? 'N/A') . "</div>\n";
            $html .= "<div class=\"summary-label\">Duration</div>\n";
            $html .= "</div>\n";
            
            $html .= "<div class=\"summary-item\">\n";
            $html .= "<div class=\"summary-number\">" . count($data['scanners']) . "</div>\n";
            $html .= "<div class=\"summary-label\">Scanners Used</div>\n";
            $html .= "</div>\n";
            
            $html .= "</div>\n";
            $html .= "</div>\n";
        }
        
        // Scanner results
        if (isset($data['scanners'])) {
            foreach ($data['scanners'] as $scanner => $results) {
                $html .= "<div class=\"section\">\n";
                $html .= "<h2>🔍 " . ucfirst(str_replace('_', ' ', $scanner)) . "</h2>\n";
                
                if (is_array($results)) {
                    $html .= $this->renderScannerResults($results);
                } else {
                    $html .= "<p>" . htmlspecialchars($results) . "</p>\n";
                }
                
                $html .= "</div>\n";
            }
        }
        
        return $html;
    }

    private function renderScannerResults(array $results): string
    {
        $html = "";
        
        if (isset($results[0]['severity'])) {
            // Vulnerability scan results
            foreach ($results as $result) {
                $severityClass = 'severity-' . $result['severity'];
                $severityLabel = ucfirst($result['severity']);
                
                $html .= "<div class=\"{$result['severity']}\">\n";
                $html .= "<h4>" . htmlspecialchars($result['type']) . "</h4>\n";
                $html .= "<p>" . htmlspecialchars($result['description']) . "</p>\n";
                $html .= "<span class=\"severity-badge {$severityClass}\">{$severityLabel}</span>\n";
                
                if (!empty($result['details'])) {
                    $html .= "<div class=\"details\">\n";
                    $html .= "<strong>Details:</strong><br>\n";
                    $html .= htmlspecialchars(json_encode($result['details'], JSON_PRETTY_PRINT));
                    $html .= "</div>\n";
                }
                
                $html .= "</div>\n";
            }
        } else {
            // Information gathering results
            foreach ($results as $key => $value) {
                $html .= "<h4>" . ucfirst(str_replace('_', ' ', $key)) . "</h4>\n";
                
                if (is_array($value)) {
                    $html .= "<div class=\"details\">\n";
                    $html .= htmlspecialchars(json_encode($value, JSON_PRETTY_PRINT));
                    $html .= "</div>\n";
                } else {
                    $html .= "<p>" . htmlspecialchars($value) . "</p>\n";
                }
            }
        }
        
        return $html;
    }

    private function arrayToXml(array $data): string
    {
        $xml = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n";
        $xml .= "<grim-scan-results>\n";
        $xml .= $this->arrayToXmlRecursive($data);
        $xml .= "</grim-scan-results>";
        
        return $xml;
    }

    private function arrayToXmlRecursive(array $data, string $indent = "  "): string
    {
        $xml = "";
        
        foreach ($data as $key => $value) {
            $safeKey = preg_replace('/[^a-zA-Z0-9_-]/', '_', $key);
            
            if (is_array($value)) {
                $xml .= "{$indent}<{$safeKey}>\n";
                $xml .= $this->arrayToXmlRecursive($value, $indent . "  ");
                $xml .= "{$indent}</{$safeKey}>\n";
            } else {
                $xml .= "{$indent}<{$safeKey}>" . htmlspecialchars($value) . "</{$safeKey}>\n";
            }
        }
        
        return $xml;
    }

    private function arrayToMarkdown(array $data): string
    {
        $markdown = "# GRIM Security Scanner Results\n\n";
        $markdown .= "**Generated:** " . date('Y-m-d H:i:s T') . "\n\n";
        
        if (isset($data['target'])) {
            $markdown .= "**Target:** " . $data['target'] . "\n";
        }
        
        if (isset($data['duration'])) {
            $markdown .= "**Duration:** " . $data['duration'] . "\n\n";
        }
        
        $markdown .= "---\n\n";
        
        if (isset($data['scanners'])) {
            foreach ($data['scanners'] as $scanner => $results) {
                $markdown .= "## " . ucfirst(str_replace('_', ' ', $scanner)) . "\n\n";
                
                if (is_array($results)) {
                    $markdown .= $this->renderMarkdownResults($results);
                } else {
                    $markdown .= $results . "\n\n";
                }
            }
        }
        
        return $markdown;
    }

    private function renderMarkdownResults(array $results): string
    {
        $markdown = "";
        
        if (isset($results[0]['severity'])) {
            // Vulnerability scan results
            foreach ($results as $result) {
                $severityIcon = $this->getSeverityIcon($result['severity']);
                $markdown .= "### {$severityIcon} " . ucfirst($result['type']) . "\n\n";
                $markdown .= "**Description:** " . $result['description'] . "\n\n";
                $markdown .= "**Severity:** " . ucfirst($result['severity']) . "\n\n";
                
                if (!empty($result['details'])) {
                    $markdown .= "**Details:**\n```json\n";
                    $markdown .= json_encode($result['details'], JSON_PRETTY_PRINT);
                    $markdown .= "\n```\n\n";
                }
                
                $markdown .= "---\n\n";
            }
        } else {
            // Information gathering results
            foreach ($results as $key => $value) {
                $markdown .= "### " . ucfirst(str_replace('_', ' ', $key)) . "\n\n";
                
                if (is_array($value)) {
                    $markdown .= "```json\n";
                    $markdown .= json_encode($value, JSON_PRETTY_PRINT);
                    $markdown .= "\n```\n\n";
                } else {
                    $markdown .= $value . "\n\n";
                }
            }
        }
        
        return $markdown;
    }

    private function getSeverityIcon(string $severity): string
    {
        return match($severity) {
            'vulnerability' => '🚨',
            'warning' => '⚠️',
            'info' => 'ℹ️',
            default => '📝'
        };
    }

    public function getSupportedFormats(): array
    {
        return ['json', 'csv', 'html', 'xml', 'markdown'];
    }

    public function exportToAllFormats(array $data, string $filename = null): array
    {
        $exportedFiles = [];
        
        foreach ($this->getSupportedFormats() as $format) {
            try {
                $method = 'exportTo' . ucfirst($format);
                $filepath = $this->$method($data, $filename);
                $exportedFiles[$format] = $filepath;
            } catch (\Exception $e) {
                $this->logger->error("Failed to export to {$format}", ['error' => $e->getMessage()]);
            }
        }
        
        return $exportedFiles;
    }
}
