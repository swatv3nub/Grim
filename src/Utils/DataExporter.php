<?php

namespace Grim\Utils;

use Grim\Config\ConfigManager;

class DataExporter
{
    private ConfigManager $config;
    private Logger $logger;
    private string $resultsDir;

    public function __construct()
    {
        $this->config = ConfigManager::getInstance();
        $this->logger = Logger::getInstance();
        $this->resultsDir = $this->config->get('scanner.results_dir', 'results/');
        
        // Create results directory if it doesn't exist
        if (!is_dir($this->resultsDir)) {
            mkdir($this->resultsDir, 0755, true);
        }
    }

    public function exportToJson(array $data, string $filename = null): string
    {
        $filename = $filename ?: 'grim_scan_' . date('Y-m-d_H-i-s');
        $filepath = $this->resultsDir . $filename . '.json';
        
        $jsonData = json_encode($data, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES);
        
        if (json_last_error() !== JSON_ERROR_NONE) {
            throw new \RuntimeException('JSON encoding failed: ' . json_last_error_msg());
        }
        
        file_put_contents($filepath, $jsonData);
        
        $this->logger->info("Results exported to JSON", ['filepath' => $filepath]);
        
        return $filepath;
    }

    public function exportToCsv(array $data, string $filename = null): string
    {
        $filename = $filename ?: 'grim_scan_' . date('Y-m-d_H-i-s');
        $filepath = $this->resultsDir . $filename . '.csv';
        
        $csvData = $this->arrayToCsv($data);
        file_put_contents($filepath, $csvData);
        
        $this->logger->info("Results exported to CSV", ['filepath' => $filepath]);
        
        return $filepath;
    }

    public function exportToHtml(array $data, string $filename = null): string
    {
        $filename = $filename ?: 'grim_scan_' . date('Y-m-d_H-i-s');
        $filepath = $this->resultsDir . $filename . '.html';
        
        $htmlData = $this->arrayToHtml($data);
        file_put_contents($filepath, $htmlData);
        
        $this->logger->info("Results exported to HTML", ['filepath' => $filepath]);
        
        return $filepath;
    }

    public function exportToXml(array $data, string $filename = null): string
    {
        $filename = $filename ?: 'grim_scan_' . date('Y-m-d_H-i-s');
        $filepath = $this->resultsDir . $filename . '.xml';
        
        $xmlData = $this->arrayToXml($data);
        file_put_contents($filepath, $xmlData);
        
        $this->logger->info("Results exported to XML", ['filepath' => $filepath]);
        
        return $filepath;
    }

    public function exportToMarkdown(array $data, string $filename = null): string
    {
        $filename = $filename ?: 'grim_scan_' . date('Y-m-d_H-i-s');
        $filepath = $this->resultsDir . $filename . '.md';
        
        $markdownData = $this->arrayToMarkdown($data);
        file_put_contents($filepath, $markdownData);
        
        $this->logger->info("Results exported to Markdown", ['filepath' => $filepath]);
        
        return $filepath;
    }

    private function arrayToCsv(array $data): string
    {
        $csv = "Type,Description,Details,Severity,Timestamp,Target\n";
        
        $this->flattenArray($data, $csv);
        
        return $csv;
    }

    private function flattenArray(array $data, string &$csv, string $prefix = ''): void
    {
        foreach ($data as $key => $value) {
            $currentKey = $prefix ? $prefix . '.' . $key : $key;
            
            if (is_array($value)) {
                $this->flattenArray($value, $csv, $currentKey);
            } else {
                $escapedValue = is_string($value) ? '"' . str_replace('"', '""', $value) . '"' : $value;
                $csv .= "{$currentKey},{$escapedValue}\n";
            }
        }
    }

