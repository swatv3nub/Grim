        $html .= "<title>GRIM Security Scanner Results</title>\n";
        $html .= "<style>\n";
        $html .= $this->getHtmlStyles();
        $html .= "</style>\n</head>\n<body>\n";
        
        $html .= "<div class=\"container\">\n";
        $html .= "<header>\n";
        $html .= "<h1>🔒 GRIM Security Scanner Results</h1>\n";
        $html .= "<p class=\"timestamp\">Generated: " . date('Y-m-d H:i:s T') . "</p>\n";
        $html .= "</header>\n";
        
        $html .= $this->generateHtmlContent($data);
        
        $html .= "<footer>\n";
        $html .= "<p>Generated by GRIM Security Scanner v3.0.0</p>\n";
        $html .= "</footer>\n";
        $html .= "</div>\n";
        
        $html .= "</body>\n</html>";
        
        return $html;
    }

